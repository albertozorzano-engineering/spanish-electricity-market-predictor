def entrenar_modelo(X: pd.DataFrame, y: pd.Series) -> tuple:
    """
    Entrena un XGBoost con split cronológico (80/20).
    Devuelve el modelo, métricas y datos de test.
    """
    print("\n" + "="*60)
    print("FASE 2: ENTRENAMIENTO DEL MODELO")
    print("="*60)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, shuffle=False  # Respetamos el tiempo — sin data leakage
    )

    modelo = xgb.XGBRegressor(
        n_estimators=400,
        max_depth=7,
        learning_rate=0.04,
        subsample=0.85,
        colsample_bytree=0.85,
        min_child_weight=3,
        random_state=42,
        n_jobs=-1
    )

    print("  🧠 Entrenando XGBoost...")
    modelo.fit(X_train, y_train,
               eval_set=[(X_test, y_test)],
               verbose=False)

    pred = modelo.predict(X_test)
    mae  = mean_absolute_error(y_test, pred)
    r2   = r2_score(y_test, pred)

    print(f"\n  📈 Resultados en test (últimas {len(y_test):,} horas):")
    print(f"     MAE  → {mae:.2f} €/MWh de error medio")
    print(f"     R²   → {r2*100:.1f}% de varianza explicada")

    return modelo, pred, y_test, mae, r2


