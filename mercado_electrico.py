def descargar_precios_ree(años: int = 3) -> pd.DataFrame:
    """
    Descarga precios horarios del mercado OMIE desde la API de REE.
    Devuelve un DataFrame con índice datetime y columna 'Precio' (€/MWh).
    """
    url = "https://apidatos.ree.es/es/datos/mercados/precios-mercados-tiempo-real"
    datos = []
    fecha_inicio = datetime.now() - relativedelta(years=años)
    fecha_inicio = fecha_inicio.replace(day=1, hour=0, minute=0, second=0)
    meses_total = años * 12

    print(f"⚡ Descargando {meses_total} meses de precios REE...")
    for i in range(meses_total):
        inicio = fecha_inicio + relativedelta(months=i)
        fin    = fecha_inicio + relativedelta(months=i+1) - relativedelta(minutes=1)

        params = {
            'start_date': inicio.strftime('%Y-%m-%dT%H:%M'),
            'end_date':   fin.strftime('%Y-%m-%dT%H:%M'),
            'time_trunc': 'hour'
        }
        try:
            r = requests.get(url, params=params,
                             headers={'Accept': 'application/json'}, timeout=15)
            if r.status_code == 200:
                for v in r.json()['included'][0]['attributes']['values']:
                    datos.append({'Fecha': v['datetime'], 'Precio': v['value']})
        except Exception as e:
            print(f"  ⚠️  Error mes {i}: {e}")
        time.sleep(0.4)

    df = pd.DataFrame(datos)
    df['Fecha'] = pd.to_datetime(df['Fecha'], utc=True)
    df = df.set_index('Fecha')
    df.index = df.index.tz_convert('Europe/Madrid').tz_localize(None)
    df = df[~df.index.duplicated(keep='first')].sort_index()
    print(f"  ✅ {len(df):,} horas descargadas")
    return df


def descargar_demanda_ree(años: int = 3) -> pd.DataFrame:
    """
    Descarga demanda horaria real desde la API de REE.
    Devuelve un DataFrame con columna 'Demanda' (MWh).
    """
    url = "https://apidatos.ree.es/es/datos/demanda/demanda-tiempo-real"
    datos = []
    fecha_inicio = datetime.now() - relativedelta(years=años)
    fecha_inicio = fecha_inicio.replace(day=1, hour=0, minute=0, second=0)
    meses_total = años * 12

    print(f"🔌 Descargando {meses_total} meses de demanda REE...")
    for i in range(meses_total):
        inicio = fecha_inicio + relativedelta(months=i)
        fin    = fecha_inicio + relativedelta(months=i+1) - relativedelta(minutes=1)

        params = {
            'start_date': inicio.strftime('%Y-%m-%dT%H:%M'),
            'end_date':   fin.strftime('%Y-%m-%dT%H:%M'),
            'time_trunc': 'hour'
        }
        try:
            r = requests.get(url, params=params,
                             headers={'Accept': 'application/json'}, timeout=15)
            if r.status_code == 200:
                for curva in r.json().get('included', []):
                    if 'real' in curva.get('type', '').lower():
                        for v in curva['attributes']['values']:
                            datos.append({'Fecha': v['datetime'], 'Demanda': v['value']})
                        break
        except Exception as e:
            print(f"  ⚠️  Error mes {i}: {e}")
        time.sleep(0.4)

    df = pd.DataFrame(datos)
    df['Fecha'] = pd.to_datetime(df['Fecha'], utc=True)
    df = df.set_index('Fecha')
    df.index = df.index.tz_convert('Europe/Madrid').tz_localize(None)
    df = df[~df.index.duplicated(keep='first')].sort_index()
    print(f"  ✅ {len(df):,} horas de demanda descargadas")
    return df


def descargar_clima_historico(ciudades: dict, años: int = 3) -> pd.DataFrame:
    """
    Descarga datos meteorológicos horarios históricos desde Open-Meteo Archive.
    Devuelve un DataFrame con temperatura, radiación y viento por ciudad.
    """
    url = "https://archive-api.open-meteo.com/v1/archive"
    fecha_fin   = datetime.now().strftime('%Y-%m-%d')
    fecha_inicio = (datetime.now() - relativedelta(years=años)).strftime('%Y-%m-%d')

    lats = ",".join(str(c['lat']) for c in ciudades.values())
    lons = ",".join(str(c['lon']) for c in ciudades.values())

    print(f"🌤️  Descargando clima histórico ({fecha_inicio} → {fecha_fin})...")
    params = {
        "latitude":  lats,
        "longitude": lons,
        "start_date": fecha_inicio,
        "end_date":   fecha_fin,
        "hourly": ["temperature_2m", "shortwave_radiation", "wind_speed_10m"],
        "timezone": "Europe/Madrid"
    }
    r = requests.get(url, params=params, timeout=60).json()

    dfs = []
    for i, ciudad in enumerate(ciudades.keys()):
        df_c = pd.DataFrame({
            'Fecha':               pd.to_datetime(r[i]['hourly']['time']),
            f'Temp_{ciudad}':      r[i]['hourly']['temperature_2m'],
            f'Radiacion_{ciudad}': r[i]['hourly']['shortwave_radiation'],
            f'Viento_{ciudad}':    r[i]['hourly']['wind_speed_10m'],
        }).set_index('Fecha')
        dfs.append(df_c)

    df_clima = pd.concat(dfs, axis=1)
    print(f"  ✅ {len(df_clima):,} horas de clima descargadas")
    return df_clima


def construir_dataset(años: int = 3) -> pd.DataFrame:
    """
    Descarga y une precios, demanda y clima en un único DataFrame limpio.
    """
    print("\n" + "="*60)
    print("FASE 1: CONSTRUCCIÓN DEL DATASET HISTÓRICO")
    print("="*60)

    df_precios = descargar_precios_ree(años)
    df_demanda = descargar_demanda_ree(años)
    df_clima   = descargar_clima_historico(CIUDADES, años)

    df = df_precios.join(df_demanda, how='inner').join(df_clima, how='inner')
    df.dropna(inplace=True)

    print(f"\n  📊 Dataset final: {len(df):,} horas | {df.shape[1]} variables")
    return df


