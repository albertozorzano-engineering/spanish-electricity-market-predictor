def predecir_manana(modelo, feature_cols: list, df_historico: pd.DataFrame) -> pd.DataFrame:
    """
    Predice la curva horaria de precios del día siguiente.
    Requiere el historial reciente para calcular los lags de precio.
    """
    print("\n" + "="*60)
    print("FASE 3: PREDICCIÓN PARA MAÑANA")
    print("="*60)

    manana = datetime.now() + timedelta(days=1)
    fecha_str = manana.strftime('%Y-%m-%d')
    print(f"  📅 Calculando curva para: {fecha_str}")

    # Descargamos previsión meteorológica de mañana
    url_fc = "https://api.open-meteo.com/v1/forecast"
    lats = ",".join(str(c['lat']) for c in CIUDADES.values())
    lons = ",".join(str(c['lon']) for c in CIUDADES.values())

    params_fc = {
        "latitude": lats, "longitude": lons,
        "start_date": fecha_str, "end_date": fecha_str,
        "hourly": ["temperature_2m", "shortwave_radiation", "wind_speed_10m"],
        "timezone": "Europe/Madrid"
    }
    r = requests.get(url_fc, params=params_fc, timeout=30).json()

    horas = pd.to_datetime(r[0]['hourly']['time'])
    df_fc = pd.DataFrame(index=horas)

    for i, ciudad in enumerate(CIUDADES.keys()):
        df_fc[f'Temp_{ciudad}']      = r[i]['hourly']['temperature_2m']
        df_fc[f'Radiacion_{ciudad}'] = r[i]['hourly']['shortwave_radiation']
        df_fc[f'Viento_{ciudad}']    = r[i]['hourly']['wind_speed_10m']

    # Intentamos descargar demanda prevista de REE para mañana
    try:
        url_dem = "https://apidatos.ree.es/es/datos/demanda/demanda-tiempo-real"
        params_dem = {
            'start_date': manana.strftime('%Y-%m-%dT00:00'),
            'end_date':   manana.strftime('%Y-%m-%dT23:59'),
            'time_trunc': 'hour'
        }
        r_dem = requests.get(url_dem, params=params_dem,
                             headers={'Accept': 'application/json'}, timeout=15).json()
        demanda_vals = []
        for curva in r_dem.get('included', []):
            if any(k in curva.get('type', '').lower() for k in ['prevista', 'programada', 'real']):
                demanda_vals = [v['value'] for v in curva['attributes']['values']]
                break
        if demanda_vals:
            df_fc['Demanda'] = demanda_vals[:24]
        else:
            # Fallback: usamos la media de la misma hora en días recientes
            df_fc['Demanda'] = df_historico['Demanda'].groupby(
                df_historico.index.hour).mean().values
    except:
        df_fc['Demanda'] = df_historico['Demanda'].groupby(
            df_historico.index.hour).mean().values

    # Calendario
    df_fc['Hora']           = df_fc.index.hour
    df_fc['Dia_Semana']     = manana.weekday()
    df_fc['Mes']            = manana.month
    df_fc['Es_FinDeSemana'] = int(manana.weekday() >= 5)

    # Lags de precio usando el historial reciente
    precios_recientes = df_historico['Precio'].sort_index().tail(200)
    df_fc['Precio_Lag_1h']   = precios_recientes.iloc[-1]   # última hora conocida
    df_fc['Precio_Lag_24h']  = precios_recientes.iloc[-24:].values if len(precios_recientes) >= 24 else precios_recientes.mean()
    df_fc['Precio_Lag_168h'] = precios_recientes.iloc[-168:-(168-24)].values if len(precios_recientes) >= 168 else precios_recientes.mean()
    df_fc['Precio_MA_24h']   = precios_recientes.iloc[-24:].mean()

    # Predicción
    df_fc = df_fc[feature_cols]
    precios_pred = modelo.predict(df_fc)
    df_fc['Precio_Predicho'] = precios_pred

    return df_fc


def panel_industrial(df_pred: pd.DataFrame):
    """
    Genera el panel de recomendación para optimización de consumo industrial.
    Identifica las 6 horas más baratas y las 6 más caras del día siguiente.
    """
    precios = df_pred['Precio_Predicho']
    precio_medio = precios.mean()

    horas_baratas = precios.nsmallest(6).index
    horas_caras   = precios.nlargest(6).index

    print("\n" + "="*60)
    print("PANEL DE OPTIMIZACIÓN INDUSTRIAL")
    print("="*60)
    print(f"  📊 Precio medio estimado mañana: {precio_medio:.1f} €/MWh")
    print(f"\n  ✅ ENCENDER MÁQUINAS (horas más baratas):")
    for h in sorted(horas_baratas):
        print(f"     {h.strftime('%H:%M')} → {precios[h]:.1f} €/MWh")
    print(f"\n  ❌ APAGAR MÁQUINAS (horas más caras):")
    for h in sorted(horas_caras):
        print(f"     {h.strftime('%H:%M')} → {precios[h]:.1f} €/MWh")

    ahorro_potencial = precios.nlargest(6).mean() - precios.nsmallest(6).mean()
    print(f"\n  💰 Diferencial precio pico/valle: {ahorro_potencial:.1f} €/MWh")

    # Gráfica del panel
    fig, ax = plt.subplots(figsize=(13, 6))
    colores = ['#E74C3C' if h in horas_caras
               else '#2ECC71' if h in horas_baratas
               else '#BDC3C7' for h in precios.index]

    ax.bar(precios.index.hour, precios.values, color=colores, edgecolor='white', linewidth=0.5)
    ax.axhline(precio_medio, color='#2C3E50', linewidth=1.5, linestyle='--',
               label=f'Precio medio: {precio_medio:.1f} €/MWh')
    ax.set_title(f"Panel de Control Industrial — {df_pred.index[0].strftime('%d/%m/%Y')}",
                 fontsize=14, fontweight='bold')
    ax.set_xlabel('Hora del día', fontsize=12)
    ax.set_ylabel('Precio estimado €/MWh', fontsize=12)
    ax.set_xticks(range(24))

    from matplotlib.patches import Patch
    leyenda = [
        Patch(color='#2ECC71', label='Encender máquinas (más barato)'),
        Patch(color='#E74C3C', label='Apagar máquinas (más caro)'),
        Patch(color='#BDC3C7', label='Horas intermedias'),
    ]
    ax.legend(handles=leyenda, loc='upper left')
    ax.grid(True, alpha=0.3, axis='y')

    plt.tight_layout()
    plt.savefig('panel_industrial_manana.png', dpi=150, bbox_inches='tight')
    plt.show()
    print("  💾 Panel guardado en: panel_industrial_manana.png")


