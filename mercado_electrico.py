def crear_features(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.Series]:
    """
    Construye las variables de entrada (X) y el objetivo (y).

    Variables incluidas:
      - Clima en 3 zonas estratégicas (temperatura, radiación solar, viento)
      - Demanda nacional horaria
      - Calendario: hora, día semana, mes, fin de semana
      - Lags de precio: precio de hace 1h, 24h (mismo slot ayer) y 168h (semana)
      - Media móvil del precio en las últimas 24h
    """
    df = df.copy().sort_index()

    # Variables de calendario
    df['Hora']          = df.index.hour
    df['Dia_Semana']    = df.index.dayofweek
    df['Mes']           = df.index.month
    df['Es_FinDeSemana'] = (df['Dia_Semana'] >= 5).astype(int)

    # Lags de precio — el mercado tiene fuerte inercia
    df['Precio_Lag_1h']   = df['Precio'].shift(1)    # hace 1 hora
    df['Precio_Lag_24h']  = df['Precio'].shift(24)   # mismo slot ayer
    df['Precio_Lag_168h'] = df['Precio'].shift(168)  # mismo slot semana pasada
    df['Precio_MA_24h']   = df['Precio'].shift(1).rolling(24).mean()  # tendencia reciente

    df.dropna(inplace=True)

    feature_cols = [c for c in df.columns if c != 'Precio']
    return df[feature_cols], df['Precio']


